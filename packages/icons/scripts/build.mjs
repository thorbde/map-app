// Turns svg/<name>.duotone.svg and svg/<name>.solid.svg into React components in
// generated/. The SVGs are drawn by tools/draw.py and approved by Thor; this script
// only checks them against the rules and converts them. `pnpm icons:check` (part of
// `pnpm check`) fails when generated/ is out of step with svg/.

import {
	mkdirSync,
	readdirSync,
	readFileSync,
	rmSync,
	writeFileSync,
} from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const svgDir = `${root}svg/`;
const outDir = `${root}generated/`;

const ELEMENTS = new Set(["svg", "path", "circle"]);
const ATTRIBUTES = new Set([
	"xmlns",
	"viewBox",
	"d",
	"cx",
	"cy",
	"r",
	"fill",
	"fill-rule",
	"stroke",
	"stroke-width",
	"stroke-linecap",
	"stroke-linejoin",
]);
const PAINTS = new Set(["none", "currentColor", "var(--color-icon-fill)"]);
const VARIANTS = ["duotone", "solid"];

const fail = (file, message) => {
	throw new Error(`${file}: ${message}`);
};

/** Checks one SVG against the rules and returns its root attributes and inner markup. */
function read(file) {
	const source = readFileSync(svgDir + file, "utf8").trim();
	const match = source.match(/^<svg([^>]*)>([\s\S]*)<\/svg>$/);
	if (!match) fail(file, "not a single <svg> element");
	const [, rootAttributes, inner] = match;
	for (const [, tag] of source.matchAll(/<\/?([a-zA-Z]+)/g)) {
		if (!ELEMENTS.has(tag)) fail(file, `<${tag}> isn't allowed`);
	}
	for (const [, name, value] of source.matchAll(/([a-zA-Z:-]+)="([^"]*)"/g)) {
		if (!ATTRIBUTES.has(name))
			fail(file, `the ${name} attribute isn't allowed`);
		if ((name === "fill" || name === "stroke") && !PAINTS.has(value)) {
			fail(
				file,
				`${name}="${value}": use currentColor or var(--color-icon-fill)`,
			);
		}
	}
	if (!/viewBox="0 0 24 24"/.test(rootAttributes))
		fail(file, "the viewBox must be 0 0 24 24");
	return {
		rootAttributes: rootAttributes.replace(/\s*(xmlns|viewBox)="[^"]*"/g, ""),
		inner,
	};
}

const camel = (name) => name.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const jsx = (markup) =>
	markup
		.replace(/\s([a-z]+(?:-[a-z]+)+)=/g, (_, name) => ` ${camel(name)}=`)
		.replace(/<(path|circle)([^>]*?)\s*\/?>/g, "<$1$2 />");
const component = (name) =>
	`${name
		.split("-")
		.map((part) => part[0].toUpperCase() + part.slice(1))
		.join("")}Icon`;

const names = [
	...new Set(
		readdirSync(svgDir)
			.filter((f) => f.endsWith(".svg"))
			.map((f) => f.split(".")[0]),
	),
].sort();

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir);
for (const name of names) {
	const variants = VARIANTS.map((variant) => {
		const file = `${name}.${variant}.svg`;
		try {
			return read(file);
		} catch (error) {
			if (error.code === "ENOENT")
				fail(file, "missing: every icon has both variants");
			throw error;
		}
	});
	const [duotone, solid] = variants.map(
		({ rootAttributes, inner }) => `<g${jsx(rootAttributes)}>${jsx(inner)}</g>`,
	);
	writeFileSync(
		`${outDir}${component(name)}.tsx`,
		`// Generated by scripts/build.mjs from svg/${name}.*.svg. Don't edit; redraw instead.
import { Icon, type IconProps } from "../src/Icon";

export function ${component(name)}(props: IconProps) {
	return (
		<Icon
			{...props}
			duotone={${duotone}}
			solid={${solid}}
		/>
	);
}
`,
	);
}
writeFileSync(
	`${outDir}index.ts`,
	`// Generated by scripts/build.mjs. Don't edit.
${names.map((name) => `export { ${component(name)} } from "./${component(name)}";`).join("\n")}
`,
);
console.log(`${names.length} icons, 2 variants each → generated/`);
